// Writes supabase/seed.sql from the shared lists (T072). The Supabase CLI runs seed.sql on the
// local stack without reading other files, so the lists are copied in; seed-sql.test.ts fails
// if the copy drifts from app/src/reference/shared-lists.seed.json.
//
// Run from the repository root: node tools/server-seed/seed-sql.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../', import.meta.url);
export const SEED_JSON = fileURLToPath(new URL('app/src/reference/shared-lists.seed.json', root));
export const SEED_SQL = fileURLToPath(new URL('supabase/seed.sql', root));

const QUOTE = '$seed$';

/**
 * @param {string} table
 * @param {{ id: string, name: string, aliases: string[], listVersion: number }[]} entries
 */
function insert(table, entries) {
  const json = `[\n${entries.map((entry) => `  ${JSON.stringify(entry)}`).join(',\n')}\n]`;
  if (json.includes(QUOTE)) throw new Error(`The seed data holds the quote tag ${QUOTE}`);
  return [
    `insert into private.${table} (id, name, aliases, list_version)`,
    `select id, name, aliases, "listVersion"`,
    `from jsonb_to_recordset(${QUOTE}${json}${QUOTE}::jsonb)`,
    `  as entry (id uuid, name text, aliases text[], "listVersion" bigint);`,
  ].join('\n');
}

/**
 * @param {{ sabhas: Parameters<typeof insert>[1], artists: Parameters<typeof insert>[1] }} lists
 * @returns {string} the text of seed.sql
 */
export function seedSql(lists) {
  return [
    '-- Generated by tools/server-seed/seed-sql.mjs from app/src/reference/shared-lists.seed.json.',
    '-- Do not edit: change the JSON and run the script again. Runs on the local stack only.',
    '',
    insert('shared_sabha', lists.sabhas),
    '',
    insert('shared_artist', lists.artists),
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(SEED_SQL, seedSql(JSON.parse(readFileSync(SEED_JSON, 'utf8'))));
}
